"""Reference guidance for a simple 2D landing maneuver."""

from abc import ABC, abstractmethod
from dataclasses import dataclass
from enum import Enum
from math import isfinite

from fast_sim.control import (
    AltitudeReference2D,
    HorizontalPositionReference2D,
)
from fast_sim.geometry import LandingGearGeometry2D
from fast_sim.models import HopperState2D


class LandingPhase2D(Enum):
    """Current phase of the landing reference profile."""

    APPROACH = "approach"
    FLARE = "flare"
    FINAL = "final"


@dataclass(frozen=True, slots=True)
class LandingGuidanceParameters2D:
    """Configuration of the first 2D landing guidance.

    Descent speeds are configured as positive magnitudes. The generated
    vertical velocity references use the world-frame sign convention and
    are therefore negative during descent.

    Units:
        target_x: m
        ground_height: m
        approach_descent_speed: m/s
        flare_height: m
        touchdown_descent_speed: m/s
    """

    target_x: float
    ground_height: float
    approach_descent_speed: float
    flare_height: float
    touchdown_descent_speed: float

    def __post_init__(self) -> None:
        values = {
            "target_x": self.target_x,
            "ground_height": self.ground_height,
            "approach_descent_speed": (
                self.approach_descent_speed
            ),
            "flare_height": self.flare_height,
            "touchdown_descent_speed": (
                self.touchdown_descent_speed
            ),
        }

        for name, value in values.items():
            if not isfinite(value):
                raise ValueError(
                    f"{name} must be finite"
                )

        if self.approach_descent_speed <= 0.0:
            raise ValueError(
                "approach_descent_speed must be > 0"
            )

        if self.flare_height <= 0.0:
            raise ValueError(
                "flare_height must be > 0"
            )

        if self.touchdown_descent_speed < 0.0:
            raise ValueError(
                "touchdown_descent_speed must be >= 0"
            )

        if (
            self.touchdown_descent_speed
            > self.approach_descent_speed
        ):
            raise ValueError(
                "touchdown_descent_speed must be <= "
                "approach_descent_speed"
            )


@dataclass(frozen=True, slots=True)
class LandingGuidanceReference2D:
    """References generated by the landing guidance."""

    phase: LandingPhase2D
    horizontal_position: HorizontalPositionReference2D
    altitude: AltitudeReference2D


class LandingGuidance2D(ABC):
    """Interface for landing guidance algorithms."""

    @abstractmethod
    def compute_references(
        self,
        time: float,
        state: HopperState2D,
    ) -> LandingGuidanceReference2D:
        """Return controller references for the current landing instant."""


class PiecewiseLandingGuidance2D(LandingGuidance2D):
    """Simple approach-and-flare landing reference generator.

    The vertical profile consists of:
        1. constant-speed approach,
        2. cubic-Hermite flare,
        3. final touchdown reference.

    The flare joins position and vertical-velocity references
    continuously.

    The horizontal reference remains fixed at target_x with zero
    horizontal velocity.
    """

    def __init__(
        self,
        parameters: LandingGuidanceParameters2D,
        *,
        geometry: LandingGearGeometry2D,
        initial_state: HopperState2D,
        start_time: float = 0.0,
    ) -> None:
        if not isfinite(start_time):
            raise ValueError(
                "start_time must be finite"
            )

        self._parameters = parameters
        self._geometry = geometry
        self._start_time = start_time
        self._initial_altitude = initial_state.pz

        self._touchdown_altitude = (
            parameters.ground_height
            + geometry.cg_to_feet
        )

        if (
            self._initial_altitude
            <= self._touchdown_altitude
        ):
            raise ValueError(
                "initial altitude must be above "
                "the upright touchdown altitude"
            )

        nominal_flare_start_altitude = (
            self._touchdown_altitude
            + parameters.flare_height
        )

        self._flare_start_altitude = min(
            self._initial_altitude,
            nominal_flare_start_altitude,
        )

        approach_distance = (
            self._initial_altitude
            - self._flare_start_altitude
        )

        self._approach_duration = (
            approach_distance
            / parameters.approach_descent_speed
        )

        flare_distance = (
            self._flare_start_altitude
            - self._touchdown_altitude
        )

        average_flare_speed = 0.5 * (
            parameters.approach_descent_speed
            + parameters.touchdown_descent_speed
        )

        self._flare_duration = (
            flare_distance
            / average_flare_speed
        )

    @property
    def parameters(
        self,
    ) -> LandingGuidanceParameters2D:
        """Return the landing-guidance configuration."""
        return self._parameters

    @property
    def geometry(self) -> LandingGearGeometry2D:
        """Return the landing-gear geometry used by the guidance."""
        return self._geometry

    @property
    def start_time(self) -> float:
        """Return the guidance start time."""
        return self._start_time

    @property
    def touchdown_altitude(self) -> float:
        """Return the upright CG altitude at ground contact."""
        return self._touchdown_altitude

    @property
    def flare_start_altitude(self) -> float:
        """Return the vertical reference at the start of flare."""
        return self._flare_start_altitude

    @property
    def approach_duration(self) -> float:
        """Return the duration of the constant-speed approach."""
        return self._approach_duration

    @property
    def flare_duration(self) -> float:
        """Return the duration of the cubic flare profile."""
        return self._flare_duration

    @property
    def flare_start_time(self) -> float:
        """Return the absolute time at which the flare starts."""
        return (
            self._start_time
            + self._approach_duration
        )

    @property
    def final_reference_time(self) -> float:
        """Return the time at which the flare profile is complete."""
        return (
            self.flare_start_time
            + self._flare_duration
        )

    def compute_references(
        self,
        time: float,
        state: HopperState2D,
    ) -> LandingGuidanceReference2D:
        """Return the current horizontal and vertical landing references.

        The current state is part of the guidance interface so later
        guidance implementations can be state-dependent. The first
        piecewise implementation follows a deterministic time profile.
        """
        if not isfinite(time):
            raise ValueError(
                "time must be finite"
            )

        if time < self._start_time:
            raise ValueError(
                "time must be >= start_time"
            )

        elapsed = time - self._start_time

        if elapsed < self._approach_duration:
            phase = LandingPhase2D.APPROACH
            altitude_reference = (
                self._approach_reference(elapsed)
            )
        elif elapsed < (
            self._approach_duration
            + self._flare_duration
        ):
            phase = LandingPhase2D.FLARE

            flare_elapsed = (
                elapsed
                - self._approach_duration
            )

            altitude_reference = (
                self._flare_reference(
                    flare_elapsed
                )
            )
        else:
            phase = LandingPhase2D.FINAL
            altitude_reference = AltitudeReference2D(
                pz=self._touchdown_altitude,
                vz=-self._parameters.touchdown_descent_speed,
            )

        horizontal_reference = (
            HorizontalPositionReference2D(
                px=self._parameters.target_x,
                vx=0.0,
            )
        )

        return LandingGuidanceReference2D(
            phase=phase,
            horizontal_position=horizontal_reference,
            altitude=altitude_reference,
        )

    def _approach_reference(
        self,
        elapsed: float,
    ) -> AltitudeReference2D:
        speed = (
            self._parameters.approach_descent_speed
        )

        return AltitudeReference2D(
            pz=(
                self._initial_altitude
                - speed * elapsed
            ),
            vz=-speed,
        )

    def _flare_reference(
        self,
        flare_elapsed: float,
    ) -> AltitudeReference2D:
        duration = self._flare_duration

        if duration <= 0.0:
            return AltitudeReference2D(
                pz=self._touchdown_altitude,
                vz=-self._parameters.touchdown_descent_speed,
            )

        s = flare_elapsed / duration

        start_position = (
            self._flare_start_altitude
        )
        end_position = (
            self._touchdown_altitude
        )

        start_velocity = (
            -self._parameters.approach_descent_speed
        )
        end_velocity = (
            -self._parameters.touchdown_descent_speed
        )

        h00 = (
            2.0 * s**3
            - 3.0 * s**2
            + 1.0
        )
        h10 = (
            s**3
            - 2.0 * s**2
            + s
        )
        h01 = (
            -2.0 * s**3
            + 3.0 * s**2
        )
        h11 = (
            s**3
            - s**2
        )

        position = (
            h00 * start_position
            + h10 * duration * start_velocity
            + h01 * end_position
            + h11 * duration * end_velocity
        )

        dh00 = (
            6.0 * s**2
            - 6.0 * s
        )
        dh10 = (
            3.0 * s**2
            - 4.0 * s
            + 1.0
        )
        dh01 = (
            -6.0 * s**2
            + 6.0 * s
        )
        dh11 = (
            3.0 * s**2
            - 2.0 * s
        )

        velocity = (
            dh00 * start_position / duration
            + dh10 * start_velocity
            + dh01 * end_position / duration
            + dh11 * end_velocity
        )

        return AltitudeReference2D(
            pz=position,
            vz=velocity,
        )
